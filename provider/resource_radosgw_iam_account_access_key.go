// Ensure provider defined types fully satisfy framework interfaces.
var _ resource.Resource = &IAMAccountAccessKeyResource{}
var _ resource.ResourceWithImportState = &IAMAccountAccessKeyResource{}

func NewIAMAccountAccessKeyResource() resource.Resource {
	return &IAMAccountAccessKeyResource{}
}

// IAMAccountAccessKeyResource manages an access key for a user within a RadosGW
// account through the IAM API (CreateAccessKey), as opposed to the Admin-Ops
// based radosgw_iam_access_key.
type IAMAccountAccessKeyResource struct {
	client    *RadosgwClient
	iamClient *IAMClient
}

type IAMAccountAccessKeyResourceModel struct {
	User       types.String `tfsdk:"user"`
	Status     types.String `tfsdk:"status"`
	AccessKey  types.String `tfsdk:"access_key"`
	SecretKey  types.String `tfsdk:"secret_key"`
	CreateDate types.String `tfsdk:"create_date"`
}

type createAccessKeyResponseXML struct {
	XMLName xml.Name `xml:"CreateAccessKeyResponse"`
	Result  struct {
		AccessKey struct {
			UserName        string `xml:"UserName"`
			AccessKeyId     string `xml:"AccessKeyId"`
			Status          string `xml:"Status"`
			SecretAccessKey string `xml:"SecretAccessKey"`
			CreateDate      string `xml:"CreateDate"`
		} `xml:"AccessKey"`
	} `xml:"CreateAccessKeyResult"`
}

// iamStatusToAPI maps the lowercase schema value to the IAM API's capitalized form.
func iamStatusToAPI(status string) string {
	if strings.EqualFold(status, "inactive") {
		return "Inactive"
	}
	return "Active"
}

func (r *IAMAccountAccessKeyResource) Metadata(ctx context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_iam_account_access_key"
}

